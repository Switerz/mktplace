@pytest.mark.parametrize("status", ["cancelled", "partially_refunded", "payment_required"])
def test_status_inelegivel_nao_entra_na_comissao(banco, status):
    """Cancelado e parcialmente reembolsado estão fora do GMV da gold; manter
    a comissão deles inflaria o numerador contra um denominador que não os tem."""
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 1000)
        _pedido(conn, 900005, "kokeshi", status, 1000,
                "2026-07-10 10:00:00", [(1, 1, 1000, 170)])

    assert _rodar(banco)[0]["marketplace_fee"] is None


