"""
MARGEM-REAL-2 — a consulta REAL do conector do ML, contra PostgreSQL real.

`test_ml_comissao_transform.py` mede as regras que não precisam de banco.
Aqui roda-se `ml_connector.QUERY` — a string exata que vai para o Data Mart —
contra um cluster descartável com tabelas sintéticas de mesma forma.

Por que não basta um fake: um duplo devolve o que se mandou, e as coisas que
podem dar errado aqui são todas do banco — a chave do join, o tipo da coluna,
a borda do `date_created::date`, o fan-out de um join 1:N. O diagnóstico do
MARGEM-REAL-1 encontrou exatamente esse tipo de armadilha: um join por
`api.ml_orders.id` devolve zero linha sem erro, e nenhum fake reproduz isso
porque o fake não conhece a diferença entre `id` e `order_id`.

Sem PostgreSQL (`PMA_TEST_PG_BIN`, `.local/postgres16` ou no PATH), SKIP.
"""
from __future__ import annotations

import pytest
from sqlalchemy import create_engine, text

from pipelines.connectors.mercadolivre import connector as ml_connector
from pipelines.tests.postgres_descartavel import (
    MOTIVO_SEM_POSTGRES,
    cluster_descartavel,
    postgres_disponivel,
)

pytestmark = pytest.mark.skipif(not postgres_disponivel(), reason=MOTIVO_SEM_POSTGRES)


DDL = """
CREATE SCHEMA IF NOT EXISTS api;
CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE api.ml_orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY,  -- surrogate: a armadilha
    order_id     bigint NOT NULL,
    brand        varchar NOT NULL,
    status       varchar NOT NULL,
    total_amount numeric,
    date_created timestamp NOT NULL
);

CREATE TABLE api.ml_order_line_items (
    order_id    bigint NOT NULL,
    line_number integer NOT NULL,
    quantity    smallint NOT NULL,
    unit_price  numeric,
    sale_fee    numeric
);

CREATE TABLE gold.ml_gestao_diaria (
    ref_date              date NOT NULL,
    brand                 varchar NOT NULL,
    gmv                   numeric,
    paid_orders           integer,
    total_units           integer,
    avg_ticket            numeric,
    unique_buyers         integer,
    new_buyers            integer,
    repeat_buyers         integer,
    repeat_buyer_rate_pct numeric,
    cancelled_orders      integer,
    cancel_rate_pct       numeric,
    delivered_shipments   integer,
    avg_delivery_days     numeric,
    seller_shipping_cost  numeric,
    shipping_pct_of_gmv   numeric,
    ad_spend              numeric,
    ad_revenue            numeric,
    ad_impressions        bigint,
    ad_clicks             bigint,
    roas                  numeric,
    acos_pct              numeric,
    ctr_pct               numeric,
    cpc                   numeric
);
"""

BRANDS = ("kokeshi", "lescent")


@pytest.fixture()
def banco():
    with cluster_descartavel() as url:
        eng = create_engine(url)
        with eng.begin() as conn:
            for stmt in filter(None, (s.strip() for s in DDL.split(";"))):
                conn.execute(text(stmt))
        yield eng
        eng.dispose()


def _gold(conn, ref_date, brand, gmv, paid_orders=10):
    conn.execute(
        text(
            "INSERT INTO gold.ml_gestao_diaria (ref_date, brand, gmv, paid_orders) "
            "VALUES (:d, :b, :g, :p)"
        ),
        {"d": ref_date, "b": brand, "g": gmv, "p": paid_orders},
    )


def _pedido(conn, order_id, brand, status, total, criado, itens):
    """`itens` = lista de (line_number, quantity, unit_price, sale_fee)."""
    conn.execute(
        text(
            "INSERT INTO api.ml_orders (order_id, brand, status, total_amount, date_created) "
            "VALUES (:o, :b, :s, :t, :c)"
        ),
        {"o": order_id, "b": brand, "s": status, "t": total, "c": criado},
    )
    for line_number, qty, price, fee in itens:
        conn.execute(
            text(
                "INSERT INTO api.ml_order_line_items "
                "(order_id, line_number, quantity, unit_price, sale_fee) "
                "VALUES (:o, :l, :q, :p, :f)"
            ),
            {"o": order_id, "l": line_number, "q": qty, "p": price, "f": fee},
        )


def _rodar(banco, date_from="2026-07-01", date_to="2026-07-31", brands=BRANDS):
    with banco.connect() as conn:
        rows = conn.execute(
            text(ml_connector.QUERY),
            {"brands": brands, "date_from": date_from, "date_to": date_to},
        ).mappings().all()
    return [dict(r) for r in rows]


def _por_chave(rows):
    return {(str(r["date"]), r["brand"]): r for r in rows}


