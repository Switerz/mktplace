def test_fee_e_multiplicado_pela_quantidade(banco):
    """`sale_fee` é por unidade: 3 unidades a 11,00 são 33,00 de comissão."""
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 300)
        _pedido(conn, 900001, "kokeshi", "paid", 300,
                "2026-07-10 10:00:00", [(1, 3, 100, 11)])

    assert float(_rodar(banco)[0]["marketplace_fee"]) == 33.0


def test_multiplos_itens_no_mesmo_pedido_somam_sem_duplicar_o_pedido(banco):
    """Join 1:N: a comissão soma os itens, mas `fee_orders` conta o pedido uma
    vez só. Se `fee_orders` contasse linhas, viraria 2 e qualquer razão
    calculada sobre ele ficaria pela metade."""
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 500)
        _pedido(conn, 900002, "kokeshi", "paid", 500, "2026-07-10 10:00:00",
                [(1, 1, 300, 50), (2, 2, 100, 15)])

    row = _rodar(banco)[0]
    assert float(row["marketplace_fee"]) == 50 + 30   # 50*1 + 15*2
    assert row["fee_orders"] == 1


def test_gold_nao_sofre_fan_out_quando_o_pedido_tem_varios_itens(banco):
    """O CTE agrega ANTES do join. Sem isso, a linha da gold se multiplicaria
    pelo número de itens e o GMV seria contado várias vezes."""
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 500)
        _pedido(conn, 900003, "kokeshi", "paid", 500, "2026-07-10 10:00:00",
                [(1, 1, 100, 10), (2, 1, 100, 10), (3, 1, 300, 30)])

    rows = _rodar(banco)
    assert len(rows) == 1
    assert float(rows[0]["gmv"]) == 500.0


def test_pedido_duplicado_na_fonte_soma_duas_vezes_e_isso_e_visivel(banco):
    """Contrato honesto: a consulta NÃO deduplica pedido.

    A fonte tem `order_id` único hoje — medido: 566.512 linhas para 566.512
    pares `(order_id, line_number)` distintos. Se isso deixar de valer, a
    comissão infla, e `fee_orders` é o que denuncia: ele conta DISTINCT, então
    a razão `marketplace_fee / fee_orders` sai fora de escala.
    """
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 1000)
        _pedido(conn, 900004, "kokeshi", "paid", 1000, "2026-07-10 10:00:00",
                [(1, 1, 1000, 170)])
        conn.execute(
            text(
                "INSERT INTO api.ml_order_line_items "
                "(order_id, line_number, quantity, unit_price, sale_fee) "
                "VALUES (900004, 1, 1, 1000, 170)"
            )
        )

    row = _rodar(banco)[0]
    assert float(row["marketplace_fee"]) == 340.0
    assert row["fee_orders"] == 1, "DISTINCT expõe a duplicata em vez de escondê-la"


