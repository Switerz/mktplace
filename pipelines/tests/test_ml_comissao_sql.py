def test_join_por_order_id_encontra_a_comissao(banco):
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 1000)
        # order_id deliberadamente distante de `id` (que será 1)
        _pedido(conn, 2000012265767110, "kokeshi", "paid", 1000,
                "2026-07-10 14:00:00", [(1, 1, 1000, 170)])

    rows = _rodar(banco)
    assert len(rows) == 1
    assert float(rows[0]["marketplace_fee"]) == 170.0
    assert rows[0]["fee_orders"] == 1


def test_contraprova_join_pelo_surrogate_devolve_zero_em_silencio(banco):
    """A armadilha, executada.

    Trocar `o.order_id` por `o.id` não levanta erro: os dois são inteiros. A
    consulta simplesmente devolve NULL de comissão para todos os dias, e uma
    carga assim gravaria NULL por toda parte parecendo ter funcionado.
    """
    with banco.begin() as conn:
        _gold(conn, "2026-07-10", "kokeshi", 1000)
        _pedido(conn, 2000012265767110, "kokeshi", "paid", 1000,
                "2026-07-10 14:00:00", [(1, 1, 1000, 170)])

    sql_errado = ml_connector.QUERY.replace("li.order_id = o.order_id", "li.order_id = o.id")
    with banco.connect() as conn:
        rows = conn.execute(
            text(sql_errado),
            {"brands": BRANDS, "date_from": "2026-07-01", "date_to": "2026-07-31"},
        ).mappings().all()

    assert len(rows) == 1, "a gold continua aparecendo — só a comissão some"
    assert rows[0]["marketplace_fee"] is None
    # E a consulta certa, no mesmo banco, acha o valor:
    assert float(_rodar(banco)[0]["marketplace_fee"]) == 170.0


